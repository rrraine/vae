# ── Constants ─────────────────────────────────────────────────────────────────
IMG_SIZE    = 72
OPENMOJI_CDN = "https://cdn.jsdelivr.net/gh/hfg-gmuend/openmoji/color/72x72/{hexcode}.png"
INDEX_FILE  = Path("emoji_index.json")
ENCODER_PATH = "emoji_encoder.keras"
DECODER_PATH = "emoji_decoder.keras"

# Groups for the search filter
EMOJI_GROUPS = [
    "All Groups",
    "smileys-emotion", "people-body", "animals-nature",
    "food-drink", "travel-places", "activities",
    "objects", "symbols", "flags"
]


# ── Helpers ───────────────────────────────────────────────────────────────────

@st.cache_data(show_spinner=False)
def load_emoji_index():
    """Load the emoji index JSON, fall back to fetching from GitHub if missing."""
    if INDEX_FILE.exists():
        with open(INDEX_FILE, encoding="utf-8") as f:
            return json.load(f)
    # Fallback: fetch metadata from GitHub at runtime
    st.info("Downloading emoji index from OpenMoji…")
    r = requests.get(
        "https://raw.githubusercontent.com/hfg-gmuend/openmoji/master/data/openmoji.json",
        timeout=15
    )
    data = r.json()
    # Keep only entries that have an emoji char and annotation
    index = [
        {"hexcode": e["hexcode"], "emoji": e.get("emoji",""), 
         "annotation": e.get("annotation",""), "group": e.get("group","")}
        for e in data if e.get("emoji") and e.get("annotation")
    ]
    return index


@st.cache_resource(show_spinner=False)
def load_models():
    """Load trained encoder + decoder. Returns (encoder, decoder) or (None, None)."""
    enc_path = Path(ENCODER_PATH)
    dec_path = Path(DECODER_PATH)
    if not enc_path.exists() or not dec_path.exists():
        return None, None
    try:
        enc = tf.keras.models.load_model(str(enc_path))
        dec = tf.keras.models.load_model(str(dec_path))
        return enc, dec
    except Exception as e:
        st.error(f"Model load error: {e}")
        return None, None


@st.cache_data(show_spinner=False)
def fetch_emoji_image(hexcode: str) -> np.ndarray:
    """Fetch a 72x72 OpenMoji PNG from CDN, return float32 RGB [0,1]."""
    url = OPENMOJI_CDN.format(hexcode=hexcode)
    resp = requests.get(url, timeout=8)
    img = Image.open(io.BytesIO(resp.content)).convert("RGBA").resize(
        (IMG_SIZE, IMG_SIZE), Image.LANCZOS
    )
    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    bg.paste(img, mask=img.split()[3])
    return np.array(bg.convert("RGB"), dtype=np.float32) / 255.0


def arr_to_pil(arr: np.ndarray, upscale: int = 4) -> Image.Image:
    """Convert float32 [0,1] numpy array to a PIL image, optionally upscaled."""
    clipped = np.clip(arr * 255, 0, 255).astype(np.uint8)
    pil = Image.fromarray(clipped)
    if upscale > 1:
        new_size = (IMG_SIZE * upscale, IMG_SIZE * upscale)
        pil = pil.resize(new_size, Image.LANCZOS)
    return pil


def encode(encoder, img_arr: np.ndarray) -> np.ndarray:
    """Encode a single image → latent mean vector."""
    batch = np.expand_dims(img_arr, 0)
    z_mean, _, _ = encoder.predict(batch, verbose=0)
    return z_mean[0]


def decode(decoder, z: np.ndarray) -> np.ndarray:
    """Decode a latent vector → image array."""
    out = decoder.predict(np.expand_dims(z, 0), verbose=0)
    return np.clip(out[0], 0, 1)


def blend_latents(z_a, z_b, alpha):
    """Spherical linear interpolation (SLERP) for smoother blending."""
    # Normalize
    norm_a = np.linalg.norm(z_a)
    norm_b = np.linalg.norm(z_b)
    a_hat  = z_a / (norm_a + 1e-8)
    b_hat  = z_b / (norm_b + 1e-8)

    dot = np.clip(np.dot(a_hat, b_hat), -1.0, 1.0)
    theta = np.arccos(dot)

    if abs(theta) < 1e-6:
        # Nearly identical, fallback to linear
        z = (1 - alpha) * z_a + alpha * z_b
    else:
        z = (math.sin((1 - alpha) * theta) / math.sin(theta)) * z_a + \
            (math.sin(alpha * theta) / math.sin(theta)) * z_b

    return z


